#!/usr/bin/env python3
"""Lists @ansible/ansible-language-server and its full runtime dependency tree
(name, version, license) as shipped in the ALS bundle, and checks the licenses
against supply-chain/npm-licenses.toml. Usage: als-licenses.py <output file>"""
import json
import pathlib
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
start = (ROOT / "node_modules/@ansible/ansible-language-server").resolve()
allowed = set(tomllib.loads((ROOT / "supply-chain/npm-licenses.toml").read_text()).get("allow", []))


def resolve(from_dir: pathlib.Path, name: str) -> pathlib.Path | None:
    # Node resolution: walk up the node_modules directories (pnpm layout).
    for parent in [from_dir, *from_dir.parents]:
        candidate = parent / "node_modules" / name
        if (candidate / "package.json").exists():
            return candidate.resolve()
    return None


seen: dict[str, tuple[str, str]] = {}
stack = [start]
problems = []
while stack:
    pkg_dir = stack.pop()
    meta = json.loads((pkg_dir / "package.json").read_text())
    key = f"{meta['name']}@{meta['version']}"
    if key in seen:
        continue
    lic = meta.get("license") or "UNKNOWN"
    if isinstance(lic, dict):
        lic = lic.get("type", "UNKNOWN")
    seen[key] = (meta["name"], lic)
    if lic not in allowed:
        problems.append(f"{key}: {lic}")
    for dep in meta.get("dependencies", {}):
        found = resolve(pkg_dir.parent if pkg_dir.parent.name != "node_modules" else pkg_dir.parent.parent, dep) \
            or resolve(pkg_dir, dep)
        if found is None:
            problems.append(f"{key}: dependency {dep} not found")
        else:
            stack.append(found)

lines = [f"{k}  {lic}" for k, (_, lic) in sorted(seen.items())]
pathlib.Path(sys.argv[1]).write_text(
    "# Packages in ansible-language-server.cjs (generated by scripts/als-licenses.py)\n"
    + "\n".join(lines) + "\n"
)
if problems:
    print("ALS bundle license problems:\n  " + "\n  ".join(problems), file=sys.stderr)
    sys.exit(1)
print(f"ALS bundle: {len(seen)} packages, all licenses allowed")
