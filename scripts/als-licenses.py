#!/usr/bin/env python3
"""Lists the npm packages that esbuild put into the ALS bundle (from its metafile)
with version and license, and checks the licenses against
supply-chain/npm-licenses.toml. Usage: als-licenses.py <metafile> <output file>"""
import json
import pathlib
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
allowed = set(tomllib.loads((ROOT / "supply-chain/npm-licenses.toml").read_text()).get("allow", []))
meta = json.loads(pathlib.Path(sys.argv[1]).read_text())


def package_root(input_path: str) -> pathlib.Path | None:
    # ".../node_modules/<name or @scope/name>/..." -> package directory (innermost)
    parts = pathlib.PurePosixPath(input_path).parts
    idx = max((i for i, p in enumerate(parts) if p == "node_modules"), default=None)
    if idx is None:
        return None
    n = 2 if parts[idx + 1].startswith("@") else 1
    return (ROOT / pathlib.PurePosixPath(*parts[: idx + 1 + n])).resolve()


seen: dict[str, str] = {}
problems = []
for inp in meta["inputs"]:
    root = package_root(inp)
    if root is None:
        problems.append(f"input outside node_modules: {inp}")
        continue
    pkg = json.loads((root / "package.json").read_text())
    key = f"{pkg['name']}@{pkg['version']}"
    if key in seen:
        continue
    lic = pkg.get("license") or "UNKNOWN"
    if isinstance(lic, dict):
        lic = lic.get("type", "UNKNOWN")
    seen[key] = lic
    if lic not in allowed:
        problems.append(f"{key}: {lic}")

lines = [f"{k}  {v}" for k, v in sorted(seen.items())]
pathlib.Path(sys.argv[2]).write_text(
    "# npm packages inside ansible-language-server.cjs (from the esbuild metafile;\n"
    "# generated by scripts/bundle-als.sh)\n" + "\n".join(lines) + "\n"
)
if problems:
    print("ALS bundle problems:\n  " + "\n  ".join(problems), file=sys.stderr)
    sys.exit(1)
print(f"ALS bundle: {len(seen)} packages, all licenses allowed")
